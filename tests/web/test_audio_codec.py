"""The IMA-ADPCM reference codec (backend/web/audio_codec.py) against the shared vectors.

tests/vectors/audio_v1.json is the single source of truth, generated by scripts/audio_vectors.py. The
TypeScript and Kotlin codecs assert the same file. The copy under android/ must stay identical.
"""

import json
import struct
import sys
from pathlib import Path

import pytest

from backend.web import audio_codec as ac

ROOT = Path(__file__).resolve().parents[2]
VECTORS = ROOT / "tests" / "vectors" / "audio_v1.json"
ANDROID_COPY = ROOT / "android" / "app" / "src" / "test" / "resources" / "audio" / "audio_v1.json"


@pytest.fixture(scope="module")
def doc():
    return json.loads(VECTORS.read_text(encoding="utf-8"))


def test_tables_are_the_standard_ima_tables(doc):
    assert len(ac.STEP_TABLE) == 89 and ac.STEP_TABLE[0] == 7 and ac.STEP_TABLE[-1] == 32767
    assert list(ac.STEP_TABLE) == sorted(ac.STEP_TABLE) and len(set(ac.STEP_TABLE)) == 89
    assert list(ac.INDEX_TABLE) == [-1, -1, -1, -1, 2, 4, 6, 8] * 2
    assert doc["step_table"] == list(ac.STEP_TABLE) and doc["index_table"] == list(ac.INDEX_TABLE)


def test_sizes_match_the_wire_format():
    assert ac.ADPCM_BLOCK_BYTES == 804 and ac.PCM16_PAYLOAD_BYTES == 3200 and ac.CHUNK_SAMPLES == 1600


def test_vector_set_is_what_the_spec_promises(doc):
    names = [v["name"] for v in doc["vectors"]]
    assert names == ["synthetic_mixed", "synthetic_quiet", "zeros", "square_full_scale"]
    assert [r["name"] for r in doc["reject_encode"]] and [r["name"] for r in doc["reject_decode"]]


@pytest.mark.parametrize("name", ["synthetic_mixed", "synthetic_quiet", "zeros", "square_full_scale"])
def test_encoder_reproduces_every_vector_byte_for_byte(doc, name):
    v = next(x for x in doc["vectors"] if x["name"] == name)
    assert ac.encode_block(v["samples"]).hex() == v["block_hex"]


@pytest.mark.parametrize("name", ["synthetic_mixed", "synthetic_quiet", "zeros", "square_full_scale"])
def test_decoder_reproduces_reference_samples_exactly(doc, name):
    v = next(x for x in doc["vectors"] if x["name"] == name)
    assert ac.decode_block(bytes.fromhex(v["block_hex"])) == v["decoded"]


@pytest.mark.parametrize("name", ["synthetic_mixed", "synthetic_quiet", "zeros", "square_full_scale"])
def test_reconstruction_error_is_within_the_bound(doc, name):
    v = next(x for x in doc["vectors"] if x["name"] == name)
    err = max(abs(a - b) for a, b in zip(v["samples"], v["decoded"]))
    assert err == v["max_abs_error"] and err <= v["max_abs_error_bound"]
    assert v["decoded"][0] == v["samples"][0]  # the header predictor is exact


def test_rejects_bad_encoder_inputs(doc):
    for case in doc["reject_encode"]:
        with pytest.raises(ValueError):
            ac.encode_block(case["samples"])
    with pytest.raises(ValueError):
        ac.encode_block([0] * 1599 + [40000])  # out of s16 range
    with pytest.raises(ValueError):
        ac.encode_block([0] * 1599 + [1.5])  # not an int


def test_rejects_bad_decoder_blocks(doc):
    for case in doc["reject_decode"]:
        with pytest.raises(ValueError):
            ac.decode_block(bytes.fromhex(case["block_hex"]))


def test_codec_roundtrip_of_arbitrary_chunk_is_stable():
    import random

    rng = random.Random(7)
    samples = [rng.randint(-32768, 32767) for _ in range(ac.CHUNK_SAMPLES)]
    once = ac.decode_block(ac.encode_block(samples))
    twice = ac.decode_block(ac.encode_block(once))
    assert once == twice  # re-encoding decoded audio reproduces it exactly


def test_frame_roundtrip_matches_vector_frames(doc):
    for v in doc["vectors"]:
        frame = bytes.fromhex(v["frame_hex"])
        assert frame[0] == 0x02
        parsed = ac.parse_frame(frame)
        assert parsed.codec == ac.CODEC_IMA_ADPCM
        assert (parsed.seq, parsed.t_ms) == (v["frame"]["seq"], v["frame"]["t_ms"])
        assert parsed.payload == bytes.fromhex(v["block_hex"])
        assert ac.pack_frame(ac.CODEC_IMA_ADPCM, parsed.seq, parsed.t_ms, parsed.payload) == frame


def test_frame_header_layout_is_little_endian():
    block = bytes(ac.ADPCM_BLOCK_BYTES)
    frame = ac.pack_frame(1, seq=0x01020304, t_ms=0x0A0B0C0D, payload=block)
    assert frame[:10] == b"\x02\x01" + struct.pack("<II", 0x01020304, 0x0A0B0C0D)


@pytest.mark.parametrize(
    "data",
    [
        b"",
        b"\x02\x01\x00\x00",  # shorter than the header
        b"\x03" + bytes(9 + ac.ADPCM_BLOCK_BYTES),  # wrong magic
        b"\x02\x02" + bytes(8 + ac.ADPCM_BLOCK_BYTES),  # codec 2 is reserved
        b"\x02\x07" + bytes(8 + ac.ADPCM_BLOCK_BYTES),  # unknown codec
        b"\x02\x01" + bytes(8 + ac.ADPCM_BLOCK_BYTES - 1),  # short block
        b"\x02\x01" + bytes(8 + ac.ADPCM_BLOCK_BYTES + 1),  # long block
        b"\x02\x00" + bytes(8 + ac.PCM16_PAYLOAD_BYTES - 2),  # short PCM16
    ],
)
def test_parse_frame_rejects_malformed_frames(data):
    with pytest.raises(ValueError):
        ac.parse_frame(data)


def test_pack_frame_rejects_out_of_range_fields():
    with pytest.raises(ValueError):
        ac.pack_frame(1, seq=2**32, t_ms=0, payload=bytes(ac.ADPCM_BLOCK_BYTES))
    with pytest.raises(ValueError):
        ac.pack_frame(1, seq=0, t_ms=-1, payload=bytes(ac.ADPCM_BLOCK_BYTES))
    with pytest.raises(ValueError):
        ac.pack_frame(0, seq=0, t_ms=0, payload=bytes(10))


def test_committed_vectors_are_the_generator_output():
    sys.path.insert(0, str(ROOT / "scripts"))
    try:
        import audio_vectors
    finally:
        sys.path.remove(str(ROOT / "scripts"))
    assert audio_vectors.render(audio_vectors.build()) == VECTORS.read_text(encoding="utf-8")


def test_android_copy_of_the_vectors_is_identical():
    assert ANDROID_COPY.read_bytes() == VECTORS.read_bytes(), (
        "android/app/src/test/resources/audio/audio_v1.json differs from tests/vectors/audio_v1.json; "
        "run: python scripts/audio_vectors.py"
    )
