"""Generate the Android app's Kotlin mirror of the pydantic contracts, and the JSON fixtures its
unit tests read.

    python scripts/gen_kotlin_types.py                             # writes into android/
    python scripts/gen_kotlin_types.py --out DIR --fixtures DIR    # writes elsewhere (used by tests)

Writes android/app/src/main/java/com/btb/ondevice/contracts/Contracts.kt (package
com.btb.ondevice.contracts) and one android/app/src/test/resources/contracts/<model>.json per model,
each being the pydantic model's own to_json() output.

tests/web/test_kotlin_types.py fails if the committed files are stale and android ContractsTest.kt
fails if the Kotlin types stop matching those fixtures, so run this after changing contracts.py.
"""

